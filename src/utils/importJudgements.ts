/**
 * Appends the provided Supreme Court and Delhi High Court judgments to the existing `MASTER_JUDGEMENTS` array.
 * Checks for duplicate IDs before appending new entries, preserving existing tags and citation formats.
 *
 * @param newJudgements Optional array of Judgement items to append. If omitted, uses SUPREME_COURT_AND_DELHI_HC_JUDGEMENTS.
 * @returns The updated MASTER_JUDGEMENTS array with newly appended judgements.
 */
export function syncMasterJudgements(newJudgements: Judgement[] = SUPREME_COURT_AND_DELHI_HC_JUDGEMENTS): Judgement[] {
  const existingIds = new Set(MASTER_JUDGEMENTS.map((j) => j.id));
  const uniqueItemsToAppend: Judgement[] = [];

  for (const item of newJudgements) {
    if (!existingIds.has(item.id)) {
      existingIds.add(item.id);
      uniqueItemsToAppend.push(item);
    }
  }

  if (uniqueItemsToAppend.length > 0) {
    MASTER_JUDGEMENTS.push(...uniqueItemsToAppend);
  }

  return MASTER_JUDGEMENTS;
}

export const importJudgements = syncMasterJudgements;

